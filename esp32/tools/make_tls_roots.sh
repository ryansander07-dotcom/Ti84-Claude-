#!/bin/sh
# Rebuild ti84_dongle/tls_roots.h from the root certificates in macOS's trust store.
# api.anthropic.com is signed by Google Trust Services; GlobalSign Root CA
# cross-signs GTS Root R4. Run this again if the dongle starts saying it
# can't verify the connection to Claude.
set -e
cd "$(dirname "$0")/.."
KEYCHAIN=/System/Library/Keychains/SystemRootCertificates.keychain
OUT=ti84_dongle/tls_roots.h
{
  echo "// Root certificates the dongle trusts for api.anthropic.com."
  echo "// Generated by tools/make_tls_roots.sh. Public certificates, not secrets."
  echo "#pragma once"
  echo "static const char TLS_ROOTS[] ="
  for name in "GTS Root R1" "GTS Root R2" "GTS Root R3" "GTS Root R4" "GlobalSign Root CA"; do
    echo "  // $name"
    security find-certificate -c "$name" -p "$KEYCHAIN" | sed 's/^/  "/; s/$/\\n"/'
  done
  echo "  ;"
} > "$OUT"
echo "Wrote $OUT"
